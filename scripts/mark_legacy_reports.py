#!/usr/bin/env python3
"""Put a LEGACY header on monthly report files written by the old report code (2026-10-14).

The old code printed an unmeasured session as "0.000 kWh", added it into the totals, gave no
provenance, and cached a file generated before its month was over. Those files are history and
are NOT regenerated: this script only PREPENDS a header that says what they are. Their body stays
byte-for-byte as it was, and their modification time — which the API lists as "generated_at" —
is preserved.

A file is legacy when it is an ADMIN report (pedestal-<id>_<YYYY>-<MM>.txt) with no "Status:" line
(the new code always writes one). Staff files are new and never legacy.

Per file the header says, from facts, not assumptions:
  * generated before the month ended  -> PARTIAL, with the generation date from the file itself;
  * the database holds MORE completed sessions that started in that month than the file has rows
    -> "this month had N completed sessions; this report shows M";
  * the SHA256 of the file as it was before the header.

DRY RUN by default: prints, per file, the SHA256 and the header it would write. --apply writes,
then re-reads each file and proves the body after the header is the original bytes (same SHA256).
Idempotent: a file that already carries the header is skipped.

Usage:
  python3 scripts/mark_legacy_reports.py --reports-dir DIR --db PEDESTAL_DB [--apply]
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import sqlite3
import sys
from datetime import date, datetime
from pathlib import Path

ADMIN_RE = re.compile(r"^pedestal-(\d+)_(\d{4})-(\d{2})\.txt$")
MARKER = "#### LEGACY REPORT"
ROW_RE = re.compile(rb"^\d{4}-\d{2}-\d{2} \d{2}:\d{2} -> ", re.M)
GEN_RE = re.compile(rb"^Generated: (\d{4}-\d{2}-\d{2})", re.M)


def _month_end(y: int, m: int) -> date:
    return date(y + 1, 1, 1) if m == 12 else date(y, m + 1, 1)


def header_for(path: Path, body: bytes, db: sqlite3.Connection, today: date) -> list[str] | None:
    m = ADMIN_RE.match(path.name)
    if not m:
        return None
    head = body[:2000]
    if MARKER.encode() in head or re.search(rb"^Status: ", head, re.M):
        return None
    pid, y, mo = int(m.group(1)), int(m.group(2)), int(m.group(3))
    shown = len(ROW_RE.findall(body))
    month = f"{y:04d}-{mo:02d}"
    in_db = db.execute(
        "SELECT COUNT(*) FROM sessions WHERE pedestal_id=? AND status='completed' "
        "AND substr(started_at,1,7)=?", (pid, month)).fetchone()[0]
    other = db.execute(
        "SELECT COUNT(*) FROM sessions WHERE pedestal_id=? AND status<>'completed' "
        "AND substr(started_at,1,7)=?", (pid, month)).fetchone()[0]
    g = GEN_RE.search(head)
    generated = date.fromisoformat(g.group(1).decode()) if g else None

    h = [f"{MARKER} — header added {today.isoformat()} by scripts/mark_legacy_reports.py;"
         " the report below it is UNCHANGED ####",
         "Generated by the OLD report code. Figures carry no provenance (meter reading or",
         "estimate), and a 0.000 kWh or 0.0 L below may mean NOT MEASURED, not 'nothing used';",
         "subtotals and totals count such zeros. This file is NOT a source for billing (the ERP",
         "bills) and is not regenerated."]
    if generated is not None and generated < _month_end(y, mo):
        h.append(f"PARTIAL: generated {generated.isoformat()}, before {month} was over.")
    if in_db > shown:
        h.append(f"INCOMPLETE: the database holds {in_db} completed session(s) that started in "
                 f"{month} (counted {today.isoformat()}); this report shows {shown}. It does not "
                 f"show all of the month's sessions.")
    if other:
        h.append(f"Also {other} session(s) started in {month} that did not end as 'completed' "
                 f"(the report never listed those).")
    h.append(f"SHA256 of this file before the header: {hashlib.sha256(body).hexdigest()}")
    h.append("#" * 72)
    return h


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--reports-dir", required=True)
    ap.add_argument("--db", required=True, help="pedestal.db (opened read-only)")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--today", help=argparse.SUPPRESS)   # tests only
    a = ap.parse_args()
    # The header contains "—"; print UTF-8 everywhere (a cp1252 console would mangle it).
    sys.stdout.reconfigure(encoding="utf-8")

    today = date.fromisoformat(a.today) if a.today else date.today()
    db = sqlite3.connect(f"file:{Path(a.db).resolve().as_posix()}?mode=ro", uri=True)
    files = sorted(p for p in Path(a.reports_dir).iterdir() if ADMIN_RE.match(p.name))
    print(("APPLY" if a.apply else "DRY RUN — nothing is written; --apply writes") + f": {len(files)} admin report file(s)")
    marked = skipped = 0
    for p in files:
        body = p.read_bytes()
        h = header_for(p, body, db, today)
        sha = hashlib.sha256(body).hexdigest()
        if h is None:
            print(f"  skip   {p.name}  sha256={sha}  (not legacy, or already marked)")
            skipped += 1
            continue
        print(f"  legacy {p.name}  sha256={sha}  size={len(body)}")
        for line in h:
            print(f"         | {line}")
        if not a.apply:
            continue
        st = p.stat()
        new = ("\n".join(h) + "\n").encode("utf-8") + body
        tmp = p.with_name(p.name + ".tmp")
        tmp.write_bytes(new)
        os.replace(tmp, p)
        os.utime(p, ns=(st.st_atime_ns, st.st_mtime_ns))     # the API lists mtime as generated_at
        after = p.read_bytes()
        tail = after[len(after) - len(body):]
        ok = after.endswith(body) and hashlib.sha256(tail).hexdigest() == sha \
            and p.stat().st_mtime_ns == st.st_mtime_ns
        print(f"         body unchanged: {'yes' if ok else 'NO'}; mtime kept: "
              f"{'yes' if p.stat().st_mtime_ns == st.st_mtime_ns else 'NO'}; "
              f"sha256 now={hashlib.sha256(after).hexdigest()}")
        if not ok:
            print("FAILED — restore this file from the copy taken in §13 R.1", file=sys.stderr)
            return 1
        marked += 1
    print(f"{'marked' if a.apply else 'would mark'}: {marked if a.apply else len(files) - skipped}; skipped: {skipped}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
